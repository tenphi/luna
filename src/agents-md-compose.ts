import { randomUUID } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { getAgentDir } from './install-paths.js';
import { readStoredContainerConfig } from './container-config.js';
import { resolveContainerSkills } from './container-skills.js';
import { isHostMcpServerWired } from './host-mcp/defaults.js';
import { APPLE_SERVER_KEYS } from './host-mcp/builtins/apple/shared/config.js';
import { isMemoryBuiltinEnabled } from './host-mcp/builtins/memory/provider.js';
import type { AgentGroup } from './types.js';

export const SHARED_AGENTS_MD_CONTAINER_PATH = '/app/container-tree/AGENTS.md';
type Fragment = { text: string } | { link: string };

function replace(destination: string, content: Fragment): void {
  if ('link' in content) {
    try {
      if (fs.readlinkSync(destination) === content.link) return;
    } catch {
      /* Create or replace the generated entry. */
    }
  }
  const temporary = `${destination}.${randomUUID()}.tmp`;
  try {
    if ('link' in content) fs.symlinkSync(content.link, temporary);
    else fs.writeFileSync(temporary, content.text, { mode: 0o600, flag: 'wx' });
    fs.renameSync(temporary, destination);
  } finally {
    fs.rmSync(temporary, { force: true });
  }
}

/** Assemble only enabled capabilities; personal instructions stay in their separate file. */
export function composeAgentsMd(group: AgentGroup): void {
  const directory = getAgentDir();
  const fragments = path.join(directory, '.agents-fragments');
  fs.mkdirSync(fragments, { recursive: true });
  const settings = readStoredContainerConfig(group);
  const wanted: Record<string, Fragment> = Object.create(null);
  const core = (name: string): void => {
    wanted[`${name}.md`] = { link: `/app/container-tree/fragments/${name}.md` };
  };
  core('tools');
  if (isMemoryBuiltinEnabled()) core('memory');
  if (settings.context?.topics?.enabled !== false) core('episodes');
  if (isHostMcpServerWired(settings.mcpServers, APPLE_SERVER_KEYS.reminders)) core('reminders');

  for (const name of resolveContainerSkills(settings)) {
    if (fs.existsSync(path.resolve('container', 'skills', name, 'instructions.md'))) {
      wanted[`skill-${encodeURIComponent(name)}.md`] = { link: `/app/skills/${name}/instructions.md` };
    }
  }
  const modules = path.resolve('container', 'agent-runner', 'src', 'mcp-tools');
  if (fs.existsSync(modules)) {
    for (const filename of fs.readdirSync(modules)) {
      if (!filename.endsWith('.instructions.md')) continue;
      const name = filename.slice(0, -'.instructions.md'.length);
      if (name === 'cli' && settings.cliScope === 'disabled') continue;
      wanted[`module-${name}.md`] = { link: `/app/src/mcp-tools/${filename}` };
    }
  }
  for (const [name, server] of Object.entries(settings.mcpServers)) {
    if (server.instructions) wanted[`mcp-${encodeURIComponent(name)}.md`] = { text: server.instructions };
  }

  for (const existing of fs.readdirSync(fragments, { withFileTypes: true })) {
    if (!Object.hasOwn(wanted, existing.name) && !existing.isDirectory())
      fs.unlinkSync(path.join(fragments, existing.name));
  }
  for (const [name, content] of Object.entries(wanted)) replace(path.join(fragments, name), content);
  replace(path.join(directory, '.agents-shared.md'), { link: SHARED_AGENTS_MD_CONTAINER_PATH });
  const imports = Object.keys(wanted)
    .sort()
    .map((name) => `@./.agents-fragments/${name}`);
  replace(path.join(directory, 'AGENTS.md'), {
    text: [
      '<!-- Generated by Luna. Keep personal instructions in AGENTS.local.md. -->',
      '@./.agents-shared.md',
      ...imports,
      '',
    ].join('\n'),
  });
  try {
    fs.writeFileSync(path.join(directory, 'AGENTS.local.md'), '', { flag: 'wx', mode: 0o600 });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
  }
}
